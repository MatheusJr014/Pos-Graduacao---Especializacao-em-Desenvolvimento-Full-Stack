#Fórmulas matematicas para o calculo: 
# Perimetro de um retangulo: P = 2 * (Comprimento + Largura)
# Area de um retangulo: A = Comprimento * Largura



#Leitura das meidadas do Terreno 
print("Digite o comprimento do terreno: ")
comprimento = float(input())

print("Digite a largura do terreno: ")
largura = float(input())

#Cálculo do perimetro  
perimetro = 2 * (comprimento + largura)

#Calculo da área 
area = comprimento * largura

#Exibição dos resultados 

print("Perimetro do terreno:", perimetro )
print("Área do terreno:", area)


