#Fórmula para o cálculo: 
#Tempo de viagem: T = distancia / velocidade

#leitura dos dados da viagem 
print("Digite a distancia da viagem (em KM):")
distancia = float(input())

print("Digite a velocidade média do veículo (em KM/h):")
velocidade = float(input())

#Cálculo do tempo de viagem 
tempo = distancia / velocidade

#Exibição do resultado 
print("O Tempo estimado da viagem é:", tempo, "horas")

